/**
 * Реквизиты и правовые данные (задача E8).
 *
 * Зачем отдельным файлом: реквизиты нужны в трёх местах сразу — в подвале,
 * в оферте и в политике обработки данных, — и разъехавшиеся реквизиты
 * в документах хуже отсутствующих.
 *
 * **Что нужно заполнить.** Юридическое название, ИНН, ОГРН/ОГРНИП и
 * юридический адрес известны только оператору. Пока поля пусты, страницы
 * и подвал просто не показывают соответствующий блок — вместо того чтобы
 * печатать «ИНН: ___». Заглушка в реквизитах — это не «почти готово»,
 * а неверные данные: ими пользуются, на них ссылаются, их цитируют
 * в претензиях.
 *
 * Для агрегатора, принимающего заявки, реквизиты — ещё и требование
 * закона о защите прав потребителей к владельцам агрегаторов, и
 * одновременно коммерческий фактор, который Яндекс считает явно.
 */
export type Requisites = {
  /** Полное юридическое наименование: «ИП Иванов Иван Иванович». */
  legalName: string;
  inn: string;
  /** ОГРН для юрлица или ОГРНИП для предпринимателя. */
  ogrn: string;
  /** Юридический адрес. */
  legalAddress: string;
};

export const REQUISITES: Requisites = {
  legalName: '',
  inn: '',
  ogrn: '',
  legalAddress: ''
};

/** Заполнены ли реквизиты настолько, чтобы их можно было показывать. */
export const hasRequisites = (): boolean =>
  !!REQUISITES.legalName.trim() && !!REQUISITES.inn.trim();

/**
 * Дата последней редакции правовых документов.
 *
 * В документах такого рода дата обязательна: без неё нельзя сказать,
 * какая редакция действовала в момент заявки. Литералом, а не
 * `new Date()`, — и это тот редкий случай, когда литерал правильный:
 * дата должна меняться вместе с текстом, а не сама по себе.
 */
export const LEGAL_REVISION_DATE = '11 сентября 2026 года';
