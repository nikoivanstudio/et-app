import { FC } from 'react';

type Props = {
  /** Готовый объект схемы. Сериализуется как есть. */
  data: object;
};

/**
 * Вывод разметки schema.org.
 *
 * Один компонент на все схемы: раньше JSON-LD вставлялся прямо в провайдер
 * приложения, из-за чего схема организации выводилась на каждой из 868
 * страниц сайта — в том числе на статьях про пещеры.
 *
 * Экранирование `<` обязательно: без него строка `</script>` внутри данных
 * закрыла бы тег раньше времени. Данные сюда приходят из констант проекта,
 * но правило дешевле соблюдать всегда, чем вспоминать о нём при первом
 * пользовательском тексте в схеме.
 */
export const JsonLd: FC<Props> = ({ data }) => (
  <script
    type='application/ld+json'
    dangerouslySetInnerHTML={{
      __html: JSON.stringify(data).replace(/</g, '\\u003c')
    }}
  />
);
