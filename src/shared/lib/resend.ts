import { Resend } from 'resend';

/**
 * Клиент почты создаётся лениво.
 *
 * Конструктор Resend бросает исключение, если ключа нет, а модуль уровня
 * `shared` тянется теперь не только маршрутами почты: заявки и переписка
 * шлют письма из своих сервисов. При инициализации на импорте окружение
 * без `RESEND_API_KEY` (предпросмотр, машина разработчика без секретов)
 * роняло весь раздел заявок целиком — вместе с формой и чатом, которым
 * почта не нужна.
 *
 * Теперь отсутствие ключа отзывается только на самой отправке, а вызывающая
 * сторона её и так страхует (см. `booking-mailer`).
 */
let client: Resend | null = null;

export const getResend = (): Resend => {
  if (!client) {
    client = new Resend(process.env.RESEND_API_KEY);
  }

  return client;
};
