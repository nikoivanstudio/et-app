/**
 * Текущий год для заголовков коммерческих страниц.
 *
 * В нише год в title — обязательный элемент: он есть у Turnado, Tururus и
 * gosha.travel, а Tripster подставляет ещё и месяц. Без него CTR
 * проигрывается механически.
 *
 * Год обязан быть вычисляемым, а не строкой в коде. До этой правки он был
 * зашит литералом — и сайт четыре года ходил с заголовком «Джип туры по
 * Крыму в 2022».
 *
 * Важно, где вызывать: `export const metadata` вычисляется один раз при
 * загрузке модуля, то есть на всё время жизни процесса — контейнер,
 * поднятый в декабре, в январе продолжил бы отдавать прошлый год. Поэтому
 * страницы с годом переведены на `generateMetadata`, которая выполняется
 * при рендере.
 *
 * Оговорка про статические страницы: на маршрутах с `dynamic = 'force-static'`
 * значение всё равно запекается на сборке. Для них год обновится с ближайшим
 * деплоем — это приемлемо, но если сайт перестанут пересобирать, стоит
 * добавить таким маршрутам `revalidate`.
 */
export const getCurrentYear = (): number => new Date().getFullYear();
