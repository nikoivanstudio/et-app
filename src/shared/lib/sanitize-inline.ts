/**
 * Санитизация коротких подписей — цены и длительности (MED-3).
 *
 * Эти значения приходят из БД и выводятся через dangerouslySetInnerHTML,
 * потому что содержат HTML-сущности (`&nbsp;`, `&#8470;`). Полноценный
 * санитайзер здесь не подходит: `duration-label-layout` рендерится и внутри
 * клиентского компонента, а тянуть в браузерный бандл парсер HTML ради двух
 * подписей неоправданно.
 *
 * Подход: экранируются символы `<` и `>`, после чего сформировать тег
 * становится невозможно — а значит невозможны и атрибуты вида `onerror`.
 * Сущности при этом продолжают работать: `&` не экранируется, а символ,
 * полученный из сущности (например, `&lt;`), в разметку уже не превращается —
 * браузер не отправляет декодированные символы обратно в разбор тегов.
 *
 * Затем возвращается небольшой набор простых тегов оформления — строго без
 * атрибутов, поэтому внедрить обработчик события через них нельзя.
 */

const SIMPLE_FORMATTING_TAGS = /&lt;(\/?(?:b|strong|i|em|br|small|sup|sub))&gt;/gi;

export const sanitizeInlineHtml = (html: string): string =>
  html
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(SIMPLE_FORMATTING_TAGS, '<$1>');
