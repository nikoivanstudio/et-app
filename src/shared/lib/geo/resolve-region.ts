import {
  findRegion,
  findRegionByPath,
  getDefaultRegion,
  type Region
} from '@/entities/region/server';

type Input = {
  /** Путь запроса без домена и параметров. */
  pathname: string;
  /** Значение cookie `et_region`, если оно есть. */
  cookieValue?: string | null;
};

/**
 * Какой регион показывать.
 *
 * Порядок важен и является решением, а не деталью:
 *
 * 1. **Адрес сильнее cookie.** Человек пришёл по ссылке из выдачи или из
 *    переписки — он должен увидеть то, что в ссылке, а не то, что выбрал
 *    полгода назад. Обратный порядок означал бы, что одна и та же ссылка
 *    показывает разным людям разное, а поисковому роботу — третье.
 * 2. **Cookie действует там, где региона в адресе нет:** главная, каталог.
 * 3. **Иначе регион по умолчанию.**
 *
 * Определения по IP здесь нет и не предполагается: IP отвечает на вопрос
 * «откуда смотрят», а регион на туристическом сайте отвечает на вопрос
 * «куда едем». Человек ищет туры по Крыму, сидя в Москве, и молчаливая
 * переадресация увела бы его не туда, куда вела ссылка. Подробности —
 * в `docs/geo/plan.md`.
 */
export const resolveRegion = ({ pathname, cookieValue }: Input): Region => {
  const byPath = findRegionByPath(pathname);

  if (byPath) {
    return byPath;
  }

  const byCookie = findRegion(cookieValue);

  // Неопубликованный регион в cookie — это либо заготовка, которую успели
  // выключить обратно, либо подставленное руками значение. И то и другое
  // показывать нельзя.
  if (byCookie?.isPublished) {
    return byCookie;
  }

  return getDefaultRegion();
};
