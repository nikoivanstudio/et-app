import { findPhoneLike } from './phone-guard';

describe('findPhoneLike: номер в переписке', () => {
  const blocked = [
    { label: 'обычная запись', text: 'Звоните +7 978 123-45-67' },
    { label: 'через восьмёрку', text: 'мой номер 8 (978) 123 45 67' },
    { label: 'без разделителей', text: 'пишите на 89781234567' },
    { label: 'без кода страны', text: 'телефон 9781234567, жду' },
    { label: 'городской из семи цифр', text: 'наберите 1234567' },
    { label: 'цифры через точки', text: 'т. 978.123.45.67' },
    {
      label: 'перенос строки внутри номера',
      text: 'номер:\n+7 978\n123 45 67'
    },
    {
      label: 'словами',
      text: 'восемь девятьсот семьдесят восемь один два три четыре пять шесть семь'
    },
    {
      label: 'словами вперемешку с цифрами',
      text: 'восемь 978 один два три 45 67'
    },
    { label: 'буквы вместо цифр', text: 'пиши на +7 9О8 1з3 45 б7' },
    { label: 'латиница вместо цифр', text: 'зовите на 8 9l8 l23 45 67' },
    { label: 'арабские цифры', text: 'номер ٨٩٧٨١٢٣٤٥٦٧' },
    { label: 'полноширинные цифры', text: 'номер ８９７８１２３４５６７' },
    { label: 'звёздочки как разделители', text: '8*978*123*45*67' },
    {
      label: 'в скобках среди текста',
      text: 'договоримся (89781234567) сегодня'
    },
    { label: 'каждая цифра через пробел', text: 'номер 8 9 7 8 1 2 3 4 5 6 7' },
    { label: 'нестандартная разбивка', text: '+7(978)12-34-567' },
    { label: 'приписка к мессенджеру', text: 'вотсап 89781234567 там удобнее' },
    {
      label: 'номер в конце длинного письма',
      text: `Здравствуйте! Очень ждём поездку, нас четверо, двое детей.
             Хотим выехать пораньше. Если удобнее, напишите на 8-978-123-45-67`
    }
  ];

  test.each(blocked)('ловит: $label', ({ text }) => {
    expect(findPhoneLike(text)).not.toBeNull();
  });

  const allowed = [
    {
      label: 'обычная фраза',
      text: 'Здравствуйте! Подскажите, тур идёт в дождь?'
    },
    { label: 'дата', text: 'Мы приедем 12.09.2026, нас четверо' },
    { label: 'две даты', text: 'Свободно 12.09.2026 15.09.2026?' },
    { label: 'дата и время', text: 'Выезд 12.09 в 07:30, подходит?' },
    { label: 'цена', text: 'Бюджет до 20 000 рублей на двоих' },
    {
      label: 'крупная сумма',
      text: 'Страховка на 1 500 000 рублей уже включена?'
    },
    {
      label: 'количество людей словами',
      text: 'Нас двое взрослых и три ребёнка'
    },
    { label: 'время словами', text: 'Можем выехать в шесть утра или в семь' },
    {
      label: 'номер дома и года',
      text: 'Мы в отеле на Ленина 12, приезжали в 2019 году'
    },
    { label: 'много букв о', text: 'Ооооооооочень ждём поездку' },
    {
      label: 'список цен через запятую',
      text: 'Могу предложить 12000, 15000 или 18000'
    },
    { label: 'прайс списком', text: 'Цены: 12000, 8000, 3500' },
    { label: 'пустая строка', text: '' },
    { label: 'диапазон часов', text: 'Тур длится 5-6 часов' }
  ];

  test.each(allowed)('пропускает: $label', ({ text }) => {
    expect(findPhoneLike(text)).toBeNull();
  });

  test('запятая без пробела номер не разрывает', () => {
    expect(findPhoneLike('пиши 8,978,123,45,67')).not.toBeNull();
  });

  test('номер после списка цен всё равно виден', () => {
    expect(findPhoneLike('Цены 12000, 15000, звоните 8 978 123-45-67')).toBe(
      '8 978 123-45-67'
    );
  });

  test('возвращает найденный фрагмент, а не весь текст', () => {
    expect(findPhoneLike('Привет, вот телефон 8 978 123-45-67 звони')).toBe(
      '8 978 123-45-67'
    );
  });
});
