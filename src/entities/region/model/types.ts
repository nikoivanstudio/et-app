/**
 * Регион: Крым, Кавказ, Алтай.
 *
 * Не строка в базе, а запись в реестре — по той же причине, по какой
 * реестром сделаны посадочные фазы E. Регион задаёт не содержимое, а
 * устройство сайта: префикс адресов, состав навигации и то, какие
 * посадочные вообще существуют. Всё это нужно на сборке, где 860 страниц
 * пререндерятся, и поход в базу из корневого layout ради таблицы на три
 * записи сделал бы сборку зависимой от неё.
 *
 * Города — наоборот, данные: их заводит и выбирает гид, на них ссылаются
 * туры и объекты. Поэтому город — таблица и внешний ключ, а связь между
 * ними — строка `city.region_slug`, которую проверяет тест.
 *
 * Подробности решения — в `docs/geo/plan.md`.
 */
export type Region = {
  /** Слаг: он же значение cookie и ключ в `city.region_slug`. */
  slug: string;
  title: string;
  /**
   * Приставка ко всем адресам региона: `''` или `/kavkaz`.
   *
   * У Крыма приставка пустая, и это не уступка легаси, а решение:
   * `/dzhip-tury/yalta` и ещё девятьсот адресов проиндексированы, а
   * перевод их на `/krym/...` — это девятьсот правил `301` и просадка
   * на переиндексации ровно после того, как фаза B индексацию вычистила.
   *
   * Без завершающей косой черты: адрес строится как `pathPrefix + path`,
   * где `path` начинается с `/`.
   */
  pathPrefix: string;
  /**
   * Отдаётся ли регион наружу.
   *
   * Выключенный регион не даёт ни посадочных, ни пунктов в переключателе,
   * ни адресов в sitemap. Это тот самый «один флаг», которым включается
   * готовый регион, и то же правило, по которому держатся выключенными
   * заготовки городов в `geo-landings.ts`: страница без реального тура
   * за ней — это заявка, которую некому исполнить.
   */
  isPublished: boolean;
};
