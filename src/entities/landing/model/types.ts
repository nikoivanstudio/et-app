import type { FaqItem } from '@/shared/lib/seo/json-ld';

/**
 * Посадочная страница фазы E.
 *
 * Один тип на три задачи — гео-страницы городов (E3), связки
 * «откуда → куда» (E4) и форматные посадочные (E5), — потому что
 * различаются они только содержимым, а механика у всех одна: заголовок,
 * уникальный вводный текст, подборка объектов, туры и заявка.
 *
 * Ключевое ограничение, ради которого этот модуль и выглядит как список
 * вручную заполненных записей, а не как генератор: **страница заводится
 * только под ту комбинацию, где есть и спрос, и чем его закрыть**.
 * Перемножить семь городов на пять форматов — это тридцать пять адресов
 * с подстановкой в один шаблон, то есть гарантированный фильтр за
 * малополезный контент. Поэтому каждая запись пишется руками и каждая
 * несёт собственный текст.
 */
export type Landing = {
  /** Последний сегмент адреса: 'bahchisaray', 'na-zakat'. */
  slug: string;
  /** Полный путь от корня — он же канонический адрес. */
  path: string;
  /**
   * Что это за посадочная — и, главное, как для неё подбираются туры.
   *
   * `geo` — город (E3): годится и тур, выезжающий отсюда, и тур,
   * заезжающий на объекты города.
   * `route` — связка «откуда → куда» (E4): годится только тур, который
   * делает и то и другое. Объединение здесь было бы подменой: на
   * `/iz-sevastopolya/mangup-kale` попали бы все севастопольские туры,
   * включая те, что на Мангуп не едут.
   * `format` — форматная страница (E5): города у неё нет, подбор идёт
   * по объектам.
   */
  kind: 'geo' | 'route' | 'format';
  /**
   * Регион из реестра `src/entities/region`.
   *
   * Посадочная выключенного региона не отдаётся ни маршрутом, ни sitemap,
   * ни блоком «смотрите также» — как и заготовка без текста. Что адрес
   * начинается с приставки своего региона, проверяет тест реестра: иначе
   * запись разъедется с маршрутом молча.
   */
  regionSlug: string;
  /** H1 страницы. */
  title: string;
  /** Заголовок вкладки и сниппета. */
  metaTitle: string;
  metaDescription: string;
  /** Надзаголовок над H1. */
  kicker?: string;
  /**
   * Вводный текст: 150–250 слов, свой у каждой страницы.
   *
   * Обязательное условие, а не пожелание: подстановка названия города
   * в общий шаблон — это и есть тот «малополезный контент», за который
   * снимают целые разделы. Абзацами, а не одной строкой.
   */
  intro: string[];
  /**
   * Слаги объектов (`Place`), которые относятся к этой странице.
   * По ним собирается блок «что посмотреть», а у гео- и форматных
   * страниц — ещё и подборка туров.
   */
  placeSlugs?: string[];
  /**
   * Куда именно ведёт связка «откуда → куда» (E4).
   *
   * Нужно потому, что `placeSlugs` у связки перечисляет объекты страницы
   * целиком, а не только цель: у «Из Ялты в Большой каньон» там стоит ещё
   * и Ай-Петри — через яйлу идёт дорога, и в блоке «что посмотреть» ему
   * место. Но подбор по всему списку выводил на страницу каньона
   * ялтинский тур, который едет на Ай-Петри и в каньон не спускается, —
   * то есть ровно ту подмену, ради которой связка считается пересечением,
   * а не объединением.
   *
   * Не задано — целью считается весь `placeSlugs`. Так устроена
   * `/iz-sevastopolya/bahchisaray`: там цель — город, и подходит тур,
   * заехавший на любой из его объектов.
   */
  destinationSlugs?: string[];
  /**
   * Город выезда — слаг из справочника `city`.
   *
   * Слаг, а не название: сопоставление шло по строке `tour.startCity`,
   * то есть посадочная «Ялта» не видела тур, у которого гид набрал
   * «г. Ялта». Ровно от этого справочник и уводит.
   */
  citySlug?: string;
  faq?: FaqItem[];
  /**
   * Опубликована ли страница.
   *
   * Выключенная запись остаётся в коде как заготовка, но не отдаётся ни
   * маршрутом, ни sitemap. Так выглядят города, откуда выезд не подтверждён
   * оператором: заявлять его на сайте, не имея подтверждения, нельзя.
   */
  isPublished: boolean;
};
