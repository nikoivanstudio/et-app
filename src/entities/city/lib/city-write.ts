import type { CityEntity } from '@/entities/city/domain';

/**
 * Что писать в пару «ключ + строка» и чего не трогать.
 *
 * Три случая, и средний — причина, по которой это отдельная функция.
 * Правило одно и для тура, и для профиля гида, поэтому живёт здесь,
 * а не в каждом из них по копии.
 *
 * 1. Город выбран — пишем ключ и название из справочника.
 * 2. Города нет, но ключ был — владелец снял город, снимаем и строку.
 * 3. Города нет и ключа не было — значит, в строке лежит то, что миграция
 *    не сумела сопоставить («Гаспра», «пос. Научный»). Возвращаем
 *    `undefined`: колонки не трогаем вовсе. Иначе сохранение любой
 *    соседней правки стирало бы город с публичной страницы, а форма
 *    показать его не может — в ней выбор из справочника.
 */
export const resolveCityWrite = (
  city: CityEntity | undefined,
  existingCityId?: number | null
): { id: number | null; title: string | null } | undefined => {
  if (city) {
    return { id: city.id, title: city.title };
  }

  if (existingCityId) {
    return { id: null, title: null };
  }

  return undefined;
};
