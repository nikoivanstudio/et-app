/**
 * Имя cookie сессии.
 *
 * Префикс `__Host-` — защита на уровне браузера (CRIT-1): браузер примет такую
 * cookie только если она выставлена с флагом Secure, с Path=/ и без атрибута
 * Domain. То есть выдать её по обычному HTTP или с чужого поддомена невозможно
 * технически, а не только по договорённости в коде.
 *
 * На http://localhost префикс работает: браузеры считают localhost
 * доверенным origin и разрешают Secure-cookie. При разработке на другом
 * http-хосте (например, по адресу в локальной сети) cookie не установится —
 * используйте localhost либо локальный HTTPS.
 */
export const SESSION_COOKIE_NAME = '__Host-session';

/** Срок жизни сессии. Один источник истины для cookie и для claim `exp` в JWT. */
export const SESSION_TTL_MS = 7 * 24 * 60 * 60 * 1000;
